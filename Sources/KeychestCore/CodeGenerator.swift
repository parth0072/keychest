import Foundation

public struct GeneratedFile: Equatable {
    /// Path relative to the output directory.
    public let path: String
    public let contents: String
}

extension GeneratedFile {
    /// Keeps generated secrets out of version control.
    static let gitignore = GeneratedFile(path: ".gitignore",
                                         contents: "# Generated by Keychest. Never commit generated secrets.\n*\n")
}

/// Turns resolved secrets into a small, dependency-free Swift package.
public struct CodeGenerator {
    public let config: Config
    private let salt: [UInt8]

    /// - Parameter salt: Injectable for deterministic tests. Defaults to a fresh random salt.
    public init(config: Config, salt: [UInt8] = Obfuscator.randomSalt()) {
        self.config = config
        self.salt = salt
    }

    public func generate(from secrets: ResolvedSecrets) -> [GeneratedFile] {
        let package = config.output.packageName
        var files = [
            GeneratedFile(path: "Package.swift", contents: packageManifest()),
            GeneratedFile(path: "Sources/\(package)/\(config.output.typeName).swift", contents: swiftSource(from: secrets)),
        ]
        if config.output.gitignore {
            files.append(.gitignore)
        }
        return files
    }

    // MARK: - Package.swift

    private func packageManifest() -> String {
        let name = config.output.packageName
        return """
        // swift-tools-version:5.5
        // Generated by Keychest. DO NOT EDIT. DO NOT COMMIT.
        import PackageDescription

        let package = Package(
            name: "\(name)",
            products: [
                .library(name: "\(name)", targets: ["\(name)"]),
            ],
            targets: [
                .target(name: "\(name)"),
            ]
        )

        """
    }

    // MARK: - Swift source

    private func swiftSource(from secrets: ResolvedSecrets) -> String {
        let type = config.output.typeName
        var out = """
        // Generated by Keychest. DO NOT EDIT. DO NOT COMMIT.
        // Values are obfuscated, not encrypted. See docs/THREAT_MODEL.md.

        """
        out += "\n"

        // Protocols (for dependency injection and tests)
        out += "public protocol \(type)GlobalProtocol {\n"
        for secret in secrets.global {
            out += "    var \(Naming.propertyName(secret.key)): String { get }\n"
        }
        out += "}\n\n"

        if !config.environmentSecrets.isEmpty {
            out += "public protocol \(type)EnvironmentProtocol {\n"
            for key in config.environmentSecrets {
                out += "    var \(Naming.propertyName(key)): String { get }\n"
            }
            out += "}\n\n"
        }

        // Namespace
        out += "public enum \(type) {\n"
        out += "    public struct Global: \(type)GlobalProtocol {\n"
        out += "        public init() {}\n"
        for secret in secrets.global {
            out += property(secret)
        }
        out += "    }\n"

        // Environment types conform to a protocol that only exists when there are environment secrets.
        let environments = config.environmentSecrets.isEmpty ? [] : secrets.environments
        for env in environments {
            out += "\n    public struct \(env.name): \(type)EnvironmentProtocol {\n"
            out += "        public init() {}\n"
            for secret in env.secrets {
                out += property(secret)
            }
            out += "    }\n"
        }
        out += "}\n\n"

        out += decoder(type: type)
        return out
    }

    private func property(_ secret: ResolvedSecret) -> String {
        let bytes = Obfuscator.encode(secret.value, salt: salt)
        return """
                public var \(Naming.propertyName(secret.key)): String {
                    \(decoderName)._decode(\(literal(bytes, indent: 12)))
                }

        """
    }

    private var decoderName: String { "_\(config.output.typeName)Decoder" }

    private func decoder(type: String) -> String {
        """
        enum \(decoderName) {
            private static let salt: [UInt8] = \(literal(salt, indent: 8))

            static func _decode(_ encoded: [UInt8]) -> String {
                var bytes = [UInt8]()
                bytes.reserveCapacity(encoded.count)
                for (index, byte) in encoded.enumerated() {
                    bytes.append(byte ^ salt[index % salt.count])
                }
                return String(decoding: bytes, as: UTF8.self)
            }
        }

        """
    }

    /// Formats bytes as a `[UInt8]` literal, 12 per line, so long values stay readable and fast to compile.
    private func literal(_ bytes: [UInt8], indent: Int) -> String {
        if bytes.isEmpty { return "[]" }
        let pad = String(repeating: " ", count: indent)
        let rows = stride(from: 0, to: bytes.count, by: 12).map { start -> String in
            let row = bytes[start..<min(start + 12, bytes.count)]
            return pad + "    " + row.map { String(format: "0x%02x", $0) }.joined(separator: ", ") + ","
        }
        return "[\n" + rows.joined(separator: "\n") + "\n" + pad + "] as [UInt8]"
    }
}
