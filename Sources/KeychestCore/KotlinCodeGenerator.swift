import Foundation

/// Turns resolved secrets into a small Kotlin/JVM Gradle module that Android apps (or any
/// JVM project) depend on. The generated API mirrors the Swift one.
public struct KotlinCodeGenerator {
    public let config: Config
    private let salt: [UInt8]

    /// - Parameter salt: Injectable for deterministic tests. Defaults to a fresh random salt.
    public init(config: Config, salt: [UInt8] = Obfuscator.randomSalt()) {
        self.config = config
        self.salt = salt
    }

    public func generate(from secrets: ResolvedSecrets) -> [GeneratedFile] {
        let kotlin = config.kotlin
        let packagePath = kotlin.packageName.replacingOccurrences(of: ".", with: "/")
        var files = [
            GeneratedFile(path: "build.gradle.kts", contents: buildScript()),
            GeneratedFile(path: "src/main/kotlin/\(packagePath)/\(kotlin.typeName).kt", contents: source(from: secrets)),
        ]
        if kotlin.gitignore {
            files.append(.gitignore)
        }
        return files
    }

    // MARK: - build.gradle.kts

    /// No `repositories` block on purpose: Android projects usually forbid them in module scripts
    /// and declare repositories once in `settings.gradle.kts`.
    private func buildScript() -> String {
        """
        // Generated by Keychest. DO NOT EDIT. DO NOT COMMIT.
        // Declare the Kotlin plugin once in your root build, for example:
        //   id("org.jetbrains.kotlin.jvm") version "<your Kotlin version>" apply false
        plugins {
            kotlin("jvm")
        }

        // Java 11 bytecode keeps the module usable from Android projects.
        java {
            sourceCompatibility = JavaVersion.VERSION_11
            targetCompatibility = JavaVersion.VERSION_11
        }

        kotlin {
            compilerOptions {
                jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_11)
            }
        }

        """
    }

    // MARK: - Kotlin source

    private func source(from secrets: ResolvedSecrets) -> String {
        let kotlin = config.kotlin
        let type = kotlin.typeName
        // Environment objects implement an interface that only exists when there are environment secrets.
        let environments = config.environmentSecrets.isEmpty ? [] : secrets.environments

        var out = """
        // Generated by Keychest. DO NOT EDIT. DO NOT COMMIT.
        // Values are obfuscated, not encrypted. See docs/THREAT_MODEL.md.
        package \(kotlin.packageName)

        """
        out += "\n"

        // Interfaces (for dependency injection and tests)
        out += "interface \(type)Global {\n"
        for secret in secrets.global {
            out += "    val \(Naming.kotlinPropertyName(secret.key)): String\n"
        }
        out += "}\n\n"

        if !config.environmentSecrets.isEmpty {
            out += "interface \(type)Environment {\n"
            for key in config.environmentSecrets {
                out += "    val \(Naming.kotlinPropertyName(key)): String\n"
            }
            out += "}\n\n"
        }

        // Namespace
        out += "object \(type) {\n"
        out += "    object Global : \(type)Global {\n"
        out += secrets.global.map(property).joined(separator: "\n")
        out += "    }\n"

        for env in environments {
            out += "\n    object \(Naming.kotlinIdentifier(env.name)) : \(type)Environment {\n"
            out += env.secrets.map(property).joined(separator: "\n")
            out += "    }\n"
        }
        out += "}\n\n"

        out += decoder()
        return out
    }

    private func property(_ secret: ResolvedSecret) -> String {
        let rows = literalRows(Obfuscator.encode(secret.value, salt: salt))
        let argument: String
        if rows.count > 1 {
            argument = "\n" + rows.map { "                " + $0 }.joined(separator: " +\n") + "\n            "
        } else {
            argument = rows[0]
        }
        return """
                override val \(Naming.kotlinPropertyName(secret.key)): String
                    get() = \(decoderName).decode(\(argument))

        """
    }

    private var decoderName: String { "_\(config.kotlin.typeName)Decoder" }

    private func decoder() -> String {
        let rows = literalRows(salt)
        let saltExpression = rows.count > 1
            ? "(\n" + rows.map { "        " + $0 }.joined(separator: " +\n") + "\n    )"
            : rows[0]
        return """
        internal object \(decoderName) {
            private val salt: ByteArray = \(saltExpression).toByteArray(Charsets.ISO_8859_1)

            fun decode(encoded: String): String {
                val data = encoded.toByteArray(Charsets.ISO_8859_1)
                val bytes = ByteArray(data.size) { index -> (data[index].toInt() xor salt[index % salt.size].toInt()).toByte() }
                return String(bytes, Charsets.UTF_8)
            }
        }

        """
    }

    /// Splits bytes into Kotlin string literals made only of `\u00XX` escapes, 16 bytes per row.
    /// Escaping every byte keeps quotes, `$` and `\` out of the source, and a string constant is
    /// far smaller and faster to compile than a byte-array literal of the same length.
    private func literalRows(_ bytes: [UInt8]) -> [String] {
        if bytes.isEmpty { return ["\"\""] }
        return stride(from: 0, to: bytes.count, by: 16).map { start in
            let row = bytes[start..<min(start + 16, bytes.count)]
            return "\"" + row.map { String(format: "\\u%04x", $0) }.joined() + "\""
        }
    }
}
